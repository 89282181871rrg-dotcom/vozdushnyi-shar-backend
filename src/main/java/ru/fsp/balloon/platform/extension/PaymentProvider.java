package ru.fsp.balloon.platform.extension;

/**
 * Точка подключения платёжной системы.
 *
 * <p>В прототипе все операции с бонусными баллами имитационные — так требует
 * постановка задачи. Но граница вынесена наружу заранее: чтобы подключить
 * реальную платёжку, достаточно написать вторую реализацию этого интерфейса
 * и объявить её бином. Ни игровое ядро, ни контроллеры при этом не меняются.
 *
 * <p>Это и есть обоснованная граница для критерия «Готовность к развитию
 * и интеграции»: реализация не требуется, требуется структура.
 */
public interface PaymentProvider {

    /** Списать бонусные баллы. Возвращает идентификатор операции у провайдера. */
    String charge(long userId, long amount, String reason);

    /** Начислить бонусные баллы. */
    String credit(long userId, long amount, String reason);

    /** Имя провайдера — попадает в журнал событий и в ответ health-check. */
    String name();
}
