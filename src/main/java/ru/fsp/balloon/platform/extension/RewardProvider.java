package ru.fsp.balloon.platform.extension;

/**
 * Точка подключения выдачи наград — лотерейных билетов, промокодов, внешних бонусов.
 *
 * <p>Сейчас награда это фрагмент внутренней коллекции. Когда появится
 * интеграция с лотерейной системой, она встанет сюда же, без изменений
 * в игровом ядре.
 */
public interface RewardProvider {

    /**
     * Выдать награду по итогам раунда.
     *
     * @return описание выданного, попадает в экран результата и в историю
     */
    String grant(long userId, long roundId, boolean won);

    String name();
}
